/** 一圈尖牙（嘴） */
function teeth(x0: number, x1: number, y: number, n: number, h: number, up = false, col = '#f4ece0'): string {
  const w = (x1 - x0) / n;
  let s = '';
  for (let i = 0; i < n; i++) {
    const x = x0 + i * w;
    s += ink(`M${x.toFixed(1)} ${y} L${(x + w / 2).toFixed(1)} ${y + (up ? -h : h)} L${(x + w).toFixed(1)} ${y} Z`, col, 1.2);
  }
  return s;
}

/** 飘落的孢子 */
function sporeDots(col: string, pts: [number, number, number][]): string {
  return pts.map(([x, y, r]) => glow(x, y, r * 2.4, col, 0.45) + dot(x, y, r, col, 0.9)).join('');
}


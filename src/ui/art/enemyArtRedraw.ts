/** 靴子（脚尖朝左） */
function boot(x: number, y: number, s = 1): string {
  return place(ink('M-14 -12 L6 -12 L8 0 L-20 0 C-22 -6 -18 -10 -14 -12 Z', BOOT, 2.4) + line('M-14 -6 L6 -6', shade(BOOT, 0.25), 1.4, 0.6), x, y, s);
}

/** 拳头 */
function fist(x: number, y: number, r = 8, skin = SKIN): string {
  return circle(x, y, r, skin, 2.4) + line(`M${x - r * 0.6} ${y - r * 0.2} L${x + r * 0.2} ${y - r * 0.5} M${x - r * 0.5} ${y + r * 0.3} L${x + r * 0.3} ${y}`, shade(skin, -0.35), 1.2, 0.8);
}

/** 锁子甲的鳞纹 */
function mail(x0: number, y0: number, x1: number, y1: number, col: string): string {
  let d = '';
  for (let y = y0; y < y1; y += 7) for (let x = x0 + ((y - y0) % 14 ? 3.5 : 0); x < x1; x += 7) d += `M${x - 3} ${y} C${x - 3} ${y + 4} ${x + 3} ${y + 4} ${x + 3} ${y} `;
  return line(d, col, 1.1, 0.6);
}


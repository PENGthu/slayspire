function eye(x: number, y: number, r: number): string {
  return glow(x, y, r * 3, '#d18ce8', 0.8) + dot(x, y, r, '#2a1030');
}

const ART: Record<string, () => string> = { ironclad, silent, regent, necrobinder, defect, osty };

export function portraitSvg(id: string): string {
  const fn = ART[id];
  if (!fn) return '';
  return doc(150, 200, `<g filter="url(#paint)">${fn()}</g>`, 8).replace('preserveAspectRatio="xMidYMid slice"', 'preserveAspectRatio="xMidYMax meet" overflow="visible"');
}

const cache = memo((id: string) => portraitSvg(id));

export function portraitUrl(id: string): string | null {
  return ART[id] ? cache(id) : null;
}
